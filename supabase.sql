create table if not exists public.orders(
 id bigint generated by default as identity primary key, product text not null,name text not null,phone text not null,city text not null,district text not null,address text not null,
 request_no text not null check(request_no ~ '^[0-9]{17}$'),request_date text not null,request_code text not null check(request_code ~ '^[0-9]{3}$'),created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
create table if not exists public.site_settings(
 id integer primary key default 1 check(id=1),logo_url text,product1_image_url text,product2_image_url text,gift_image_url text,updated_at timestamptz default now()
);
alter table public.site_settings enable row level security;
insert into public.site_settings(id) values(1) on conflict(id) do nothing;
insert into storage.buckets(id,name,public) values('site-media','site-media',true) on conflict(id) do update set public=true;
