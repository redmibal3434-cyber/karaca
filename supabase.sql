create table if not exists public.orders(id bigint generated by default as identity primary key,product text not null,name text not null,phone text not null,city text not null,district text not null,address text not null,request_no text not null check(request_no ~ '^[0-9]{17}$'),request_date text not null check(request_date ~ '^(0[1-9]|1[0-2])/[0-9]{2}$'),created_at timestamptz not null default now()); alter table public.orders enable row level security;
alter table public.orders drop constraint if exists orders_request_code_check;
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'orders' and column_name = 'request_code'
  ) then
    alter table public.orders alter column request_code drop not null;
  end if;
end $$;
